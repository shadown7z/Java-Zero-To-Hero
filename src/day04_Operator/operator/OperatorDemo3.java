package day04_Operator.operator;

public class OperatorDemo3 {
    public static void main(String[] args) {
        /*
        赋值运算符

        1.基本赋值运算符 =
        2.扩展赋值运算符 += -= *= /= %=

        +=，左右两边做加法，并赋值给左边的变量，其他一样
         */
        int a = 10;
        a += 20;
        System.out.println(a);
    }
}
