package day04_Operator.operator;

public class OperatorDemo4 {
    public static void main(String[] args) {
        /*
        关系运算符：
            >
            >=
            <
            <=
            ==
            !=
         */
        System.out.println(10 > 20);            // false
        System.out.println(10 >= 20);           // false
        System.out.println(10 < 20);            // true
        System.out.println(10 <= 20);           // true
        System.out.println(10 == 20);           // false
        System.out.println(10 != 20);           // true
    }
}
