package day07_Arrray;

public class ArrayDemo3 {
    public static void main(String[] args) {
        /*
        数组的遍历：
        通用格式：
        for(int i = 0; i < arr.length;i++){
            System.out.println(arr[i]);
        }

        快捷打:
            数组名.fori + 回车
         */
        int[] arr = {11,22,33,44,55};
        for(int i = 0 ; i <arr.length ; i++){
            System.out.println(arr[i]);
        }
    }
}
